#!/usr/bin/env python3
"""Rebuild Meridian/Locales/enUS.lua (the complete key list) from every L["..."] in the addon code.
Run from the repo root: python3 tools/extract_strings.py"""
import glob, re

keys = []
for path in sorted(glob.glob("Meridian/*.lua")):
    for m in re.finditer(r'\bL\["((?:[^"\\]|\\.)*)"\]', open(path).read()):
        if m.group(1) not in keys:
            keys.append(m.group(1))

with open("Meridian/Locales/enUS.lua", "w") as f:
    f.write("-- English: the source strings. Generated by tools/extract_strings.py; do not edit by hand.\n")
    f.write("-- Other locales copy these keys and translate the values.\n")
    f.write("local ADDON, M = ...\nlocal L = M.L\n\n")
    for k in keys:
        f.write('L["%s"] = "%s"\n' % (k, k))
print("wrote", len(keys), "strings")
