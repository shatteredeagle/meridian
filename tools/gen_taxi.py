"""Generates Meridian/FlightData.lua from the TaxiNodes DB2 of the installed Forever build (names and positions only).
usage: sh tools/pixelmap/fetch_db2.sh OUT_DIR 1.60.1.70450 && python3 tools/gen_taxi.py OUT_DIR/TaxiNodes.csv"""
import csv, sys

rows = []
for r in csv.DictReader(open(sys.argv[1], encoding="utf-8")):
    name = r["Name_lang"]
    if r["ContinentID"] not in ("0", "1") or name.startswith("Quest Path") or name.startswith("Programmer"):
        continue
    faction = {"1025": "A", "1026": "H"}.get(r["Flags"], "")
    rows.append((name, int(r["ContinentID"]), float(r["Pos_0"]), float(r["Pos_1"]), faction))
rows.sort(key=lambda t: (t[1], t[0]))
out = ["-- Flight points of the Forever build: name, world id, world x, world y, faction (A / H / none = both).",
       "-- Generated by tools/gen_taxi.py from the TaxiNodes DB2; do not edit by hand.",
       "local ADDON, M = ...", "M.FlightData = {"]
for n, c, x, y, f in rows:
    out.append('    { "%s", %d, %.2f, %.2f%s },' % (n.replace('"', '\\"'), c, x, y, ', "%s"' % f if f else ""))
out.append("}")
open("Meridian/FlightData.lua", "w", encoding="utf-8").write("\n".join(out) + "\n")
print(len(rows), "nodes")
