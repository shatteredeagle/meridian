#!/usr/bin/env python3
"""Generates Meridian/RevealData.lua: every zone map's explored-area overlay pieces, from the game's own WorldMapOverlay
tables (file IDs and positions only, no art), so "Reveal map" works without any other addon.

Each entry is { { fileDataID, ... }, width, height, offsetX, offsetY } in zone-art pixels, the tile IDs in row-major order.
usage: python3 tools/gen_reveal.py DB2_DIR   (CSVs from tools/pixelmap/fetch_db2.sh for the Forever build)
"""
import csv, os, sys

DB2 = sys.argv[1]
def table(n): return list(csv.DictReader(open(os.path.join(DB2, n + ".csv"), encoding="utf-8")))

arts = {}
for r in table("UiMapXMapArt"):
    if r["PhaseID"] == "0":
        arts.setdefault(r["UiMapID"], []).append(r["UiMapArtID"])
ov_by_art = {}
for r in table("WorldMapOverlay"):
    ov_by_art.setdefault(r["UiMapArtID"], []).append(r)
tiles = {}
for r in table("WorldMapOverlayTile"):
    if r["LayerIndex"] == "0":
        tiles.setdefault(r["WorldMapOverlayID"], []).append((int(r["RowIndex"]), int(r["ColIndex"]), int(r["FileDataID"])))

out = ["-- Explored-area overlay pieces of every zone map, from the game's WorldMapOverlay tables (IDs and positions only).",
       "-- Generated by tools/gen_reveal.py; do not edit by hand. { { file IDs, row-major }, width, height, offsetX, offsetY }.",
       "local ADDON, M = ...", "M.RevealData = {"]
count = 0
for ui in sorted(arts, key=int):
    cands = [a for a in arts[ui] if a in ov_by_art]
    if not cands:
        continue
    art = max(cands, key=lambda a: len(ov_by_art[a]))
    entries = []
    for o in ov_by_art[art]:
        t = sorted(tiles.get(o["ID"], []))
        if not t:
            continue
        entries.append("{ {%s}, %s, %s, %s, %s }" % (",".join(str(f) for _, _, f in t), o["TextureWidth"], o["TextureHeight"], o["OffsetX"], o["OffsetY"]))
    if entries:
        out.append("    [%s] = { %s }," % (ui, ", ".join(entries)))
        count += 1
out.append("}")
open("Meridian/RevealData.lua", "w").write("\n".join(out) + "\n")
print(count, "maps")
